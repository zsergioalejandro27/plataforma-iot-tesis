-- Catálogo fijo de planes — define cuántos dispositivos puede tener un
-- tenant y cuántas lecturas puede recibir cada dispositivo. No son pagos
-- reales, es para demostrar el concepto de límites diferenciados por plan.
create table public.plans (
  id text not null,
  name text not null,
  max_devices int not null,
  max_readings_per_device int not null,
  constraint plans_pkey primary key (id)
);

insert into public.plans (id, name, max_devices, max_readings_per_device) values
  ('basico', 'Básico', 3, 10),
  ('medio', 'Medio', 5, 25),
  ('pro', 'Pro', 10, 50);

create table public.tenants (
  id uuid not null default gen_random_uuid(),
  name text not null,
  plan_id text not null default 'basico',
  plan_selected boolean not null default false,
  created_at timestamp with time zone default now(),
  constraint tenants_pkey primary key (id),
  constraint tenants_plan_id_fkey foreign key (plan_id) references public.plans (id)
);

create table public.profiles (
  id uuid not null,
  tenant_id uuid,
  full_name text,
  role text default 'member',
  created_at timestamp with time zone default now(),
  constraint profiles_pkey primary key (id),
  constraint profiles_id_fkey foreign key (id) references auth.users (id),
  constraint profiles_tenant_id_fkey foreign key (tenant_id) references public.tenants (id)
);

create table public.devices (
  id uuid not null default gen_random_uuid(),
  tenant_id uuid default get_my_tenant_id(),
  name text not null,
  device_key text not null,
  status text default 'offline',
  created_at timestamp with time zone default now(),
  metric_key text,
  unit text,
  constraint devices_pkey primary key (id),
  constraint devices_device_key_key unique (device_key),
  constraint devices_tenant_id_fkey foreign key (tenant_id) references public.tenants (id)
);

create table public.telemetry (
  id bigint generated by default as identity,
  tenant_id uuid,
  device_id uuid,
  payload jsonb not null,
  recorded_at timestamp with time zone default now(),
  constraint telemetry_pkey primary key (id),
  constraint telemetry_tenant_id_fkey foreign key (tenant_id) references public.tenants (id),
  constraint telemetry_device_id_fkey foreign key (device_id) references public.devices (id) on delete cascade
);

