-- =====================================================================
-- Migración 2026-11-09: exportar lecturas a CSV con límite diario por plan
-- =====================================================================
-- Pegar completo en Supabase → SQL Editor → Run. Se puede correr una sola
-- vez; ya está incluido en schema.sql para reconstrucciones desde cero.
--
-- Básico: 1 exportación al día · Medio: 2 · Pro: 3
-- El límite es por organización (tenant) y usa una ventana móvil de 24 h,
-- igual que el de lecturas.
-- =====================================================================

-- 1. Cuántas exportaciones permite cada plan.
alter table public.plans
  add column max_exports_per_day int not null default 1;

update public.plans
   set max_exports_per_day = case id
     when 'basico' then 1
     when 'medio'  then 2
     when 'pro'    then 3
   end;

-- 2. Registro de cada exportación hecha. Sirve para contar el cupo y como
--    historial. Si se borra el dispositivo, el registro se queda (device_id
--    pasa a null): así borrar un dispositivo no "devuelve" exportaciones.
create table public.exports (
  id bigint generated by default as identity,
  tenant_id uuid not null,
  device_id uuid,
  row_count int not null default 0,
  created_at timestamp with time zone not null default now(),
  constraint exports_pkey primary key (id),
  constraint exports_tenant_id_fkey foreign key (tenant_id) references public.tenants (id),
  constraint exports_device_id_fkey foreign key (device_id) references public.devices (id) on delete set null
);

create index exports_tenant_created_idx on public.exports (tenant_id, created_at desc);

-- 3. RLS: cada organización ve solo sus exportaciones, y NADIE puede
--    insertar, editar ni borrar directamente (si pudieran, borrarían sus
--    registros para saltarse el límite). Solo la función de abajo inserta.
alter table public.exports enable row level security;

create policy "usuarios ven exportaciones de su tenant"
  on public.exports for select
  to authenticated
  using (tenant_id = get_my_tenant_id());

revoke insert, update, delete on public.exports from anon, authenticated;

-- 4. Registra una exportación si queda cupo. La llama /api/export/[id] justo
--    antes de entregar el CSV. Devuelve cuántas exportaciones quedan.
create or replace function public.register_export(p_device_id uuid, p_row_count int)
 returns int
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_tenant uuid := get_my_tenant_id();
  v_max int;
  v_used int;
begin
  if v_tenant is null then
    raise exception 'Sesión no válida';
  end if;

  if not exists (select 1 from devices where id = p_device_id and tenant_id = v_tenant) then
    raise exception 'Dispositivo no encontrado';
  end if;

  -- "for update" bloquea la fila de la organización hasta terminar: si llegan
  -- dos clics al mismo tiempo, el segundo espera y ya ve la primera exportación
  -- contada, así no pueden pasar los dos con un solo cupo libre.
  select p.max_exports_per_day into v_max
    from tenants t join plans p on p.id = t.plan_id
   where t.id = v_tenant
     for update of t;

  select count(*) into v_used
    from exports
   where tenant_id = v_tenant
     and created_at >= now() - interval '1 day';

  if v_used >= v_max then
    raise exception 'Límite de exportaciones diarias alcanzado para tu plan (máx. % por día).', v_max;
  end if;

  insert into exports (tenant_id, device_id, row_count)
  values (v_tenant, p_device_id, greatest(p_row_count, 0));

  return v_max - v_used - 1;
end;
$function$;

revoke execute on function public.register_export(uuid, int) from public, anon;
grant execute on function public.register_export(uuid, int) to authenticated;
