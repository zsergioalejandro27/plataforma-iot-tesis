create policy "cualquiera puede ver los planes"
  on public.plans for select
  to public
  using (true);

create policy "usuarios ven su propio tenant"
  on public.tenants for select
  to public
  using (id = get_my_tenant_id());

create policy "usuarios actualizan su propio tenant"
  on public.tenants for update
  to public
  using (id = get_my_tenant_id())
  with check (id = get_my_tenant_id());

create policy "usuarios ven su propio perfil"
  on public.profiles for select
  to public
  using (id = auth.uid());

create policy "usuarios ven dispositivos de su tenant"
  on public.devices for select
  to public
  using (tenant_id = get_my_tenant_id());

create policy "usuarios crean dispositivos en su tenant"
  on public.devices for insert
  to public
  with check (tenant_id = get_my_tenant_id());

create policy "usuarios eliminan dispositivos de su tenant"
  on public.devices for delete
  to public
  using (tenant_id = get_my_tenant_id());

create policy "usuarios ven telemetria de su tenant"
  on public.telemetry for select
  to public
  using (tenant_id = get_my_tenant_id());
