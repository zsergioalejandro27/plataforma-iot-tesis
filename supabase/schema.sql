-- ---------------------------------------------------------------------
-- Funciones (van primero: `devices.tenant_id` usa get_my_tenant_id()
-- como default, así que la función debe existir antes de crear la tabla)
-- ---------------------------------------------------------------------

-- Devuelve el tenant_id del usuario autenticado actual. Se usa dentro
-- de las políticas RLS y como default de tenant_id en `devices`.
create or replace function public.get_my_tenant_id()
 returns uuid
 language sql
 stable security definer
as $function$
  select tenant_id from profiles where id = auth.uid();
$function$;

-- Se ejecuta automáticamente (vía el trigger de más abajo) cada vez que
-- alguien se registra: crea su tenant y su perfil como admin de ese
-- tenant. Es lo que hace que cada usuario nuevo "funde" su propia
-- organización sin lógica de tenant hardcodeada en el código de la app.
create or replace function public.handle_new_user()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  new_tenant_id uuid;
begin
  insert into tenants (name)
  values (coalesce(new.raw_user_meta_data->>'full_name', new.email) || ' - Organización')
  returning id into new_tenant_id;

  insert into profiles (id, tenant_id, full_name, role)
  values (new.id, new_tenant_id, new.raw_user_meta_data->>'full_name', 'admin');

  return new;
end;
$function$;

